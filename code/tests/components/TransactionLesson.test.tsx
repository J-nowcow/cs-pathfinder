// @vitest-environment happy-dom
import { act, cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { TransactionLesson } from '@/components/study-poc/TransactionLesson'
import { ConnectedLearningFlow } from '@/components/study-poc/ConnectedLearningFlow'

afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.useRealTimers() })
const next = () => fireEvent.click(screen.getByRole('button', { name: '다음 장면' }))
const goTo = (steps: number) => { for (let index = 0; index < steps; index++) next() }
const pool = () => screen.getByRole('region', { name: '연결 점유와 트랜잭션' })
const app = () => screen.getByRole('region', { name: '요청과 풀 대기' })
describe('connected transaction lesson', () => {
  it('keeps one five-concept path and focuses the next lesson without creating storage', () => {
    const save = vi.spyOn(Storage.prototype, 'setItem')
    render(<ConnectedLearningFlow />)
    expect(screen.getAllByRole('list', { name: '학습 흐름' })).toHaveLength(1)
    expect(screen.queryByRole('list', { name: '살펴볼 순서' })).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: '도입 건너뛰고 트랜잭션 보기 →' }))
    expect(document.activeElement).toBe(screen.getByRole('heading', { name: '트랜잭션 시작 전' }))
    expect(screen.getByText('새 사례이므로 요청과 연결 번호도 R1·C1부터 다시 시작합니다.')).toBeTruthy()
    expect(screen.getByRole('status').textContent).toContain('숫자를 1 늘리는 새 요청 3개')
    expect(screen.queryByText(/이 조건에서 가능한 흐름입니다/)).toBeNull()
    expect(save).not.toHaveBeenCalled()
  })
  it('asks for a prediction before exposing comparisons and keeps the committed connection borrowed until a separate release', () => {
    render(<TransactionLesson onBack={() => {}} />)
    goTo(5)
    expect(app().textContent).toContain('R3풀에서 연결 기다림')
    expect(pool().textContent).toContain('R2에 빌려줌행 잠금 기다림')
    expect(screen.queryByRole('button', { name: '조건을 바꿔 비교하기' })).toBeNull()
    const prediction = screen.getByRole('group', { name: /처음 본 조건에서 예측/ })
    expect(within(prediction).getByRole('button', { name: '선택과 이유 확인' })).toHaveProperty('disabled', true)
    fireEvent.click(within(prediction).getByRole('radio', { name: 'C3를 빌리고 7번 행의 잠금을 기다린다' }))
    fireEvent.click(within(prediction).getByRole('button', { name: '선택과 이유 확인' }))
    expect(within(prediction).getByRole('status').textContent).toContain('R3는 C3를 빌린 뒤 7번 행의 잠금을 기다립니다')
    fireEvent.click(screen.getByRole('button', { name: '조건을 바꿔 비교하기' }))
    expect(screen.queryByRole('radio', { name: '서로 다른 7·8·9번 행' })).toBeNull()
    fireEvent.click(screen.getByRole('radio', { name: '3개' }))
    expect(app().textContent).toContain('R3C3 사용 중')
    expect(screen.getByRole('region', { name: 'DB의 행 잠금' }).textContent).toContain('R2(C2), R3(C3) 잠금 기다림')
    fireEvent.click(screen.getByRole('radio', { name: '2개' }))
    next()
    expect(pool().querySelector('.sp-flow-connection')?.textContent).toContain('C1R1에 빌려줌트랜잭션 종료 · 앱이 보유')
    expect(app().textContent).toContain('R3풀에서 연결 기다림')
    next(); expect(pool().querySelector('.sp-flow-connection')?.textContent).toContain('C1풀에서 보관사용 가능')
  })
  it('reveals transfer feedback only after selection and unlocks other-row and rollback experiments', () => {
    render(<TransactionLesson onBack={() => {}} />)
    goTo(12)
    const prediction = screen.getByRole('group', { name: /별개의 새 상황/ })
    expect(screen.queryByText(/이 조건에서 가능한 흐름입니다/)).toBeNull()
    fireEvent.click(within(prediction).getByRole('radio', { name: '42번 행의 UPDATE를 진행할 수 있다' }))
    fireEvent.click(within(prediction).getByRole('button', { name: '선택과 이유 확인' }))
    fireEvent.click(screen.getByRole('button', { name: '조건을 바꿔 비교하기' }))
    fireEvent.click(screen.getByRole('radio', { name: '서로 다른 7·8·9번 행' }))
    fireEvent.click(screen.getByRole('radio', { name: 'ROLLBACK · 취소' }))
    fireEvent.click(screen.getByRole('button', { name: '이 조건으로 처음부터 보기' }))
    goTo(6)
    const db = screen.getByRole('region', { name: 'DB의 행 잠금' })
    expect(db.textContent).toContain('R1의 변경: 취소됨')
    expect(pool().textContent).not.toContain('행 잠금 기다림')
    expect(db.textContent).toContain('id = 8')
  })
  it('does not reissue the original prediction after comparison closes or the selected conditions replay', () => {
    const save = vi.spyOn(Storage.prototype, 'setItem')
    render(<TransactionLesson onBack={() => {}} />)
    goTo(5)
    const prediction = screen.getByRole('group', { name: /처음 본 조건에서 예측/ })
    fireEvent.click(within(prediction).getByRole('radio', { name: 'C3를 빌리면 UPDATE가 바로 끝난다' }))
    fireEvent.click(within(prediction).getByRole('button', { name: '선택과 이유 확인' }))
    expect(within(prediction).getByRole('status').textContent).toContain('R3는 C3를 빌린 뒤 7번 행의 잠금을 기다립니다')
    const compare = screen.getByRole('button', { name: '조건을 바꿔 비교하기' })
    fireEvent.click(compare)
    fireEvent.click(screen.getByRole('radio', { name: '3개' }))
    fireEvent.click(compare)
    expect(screen.queryByRole('group', { name: /처음 본 조건에서 예측/ })).toBeNull()
    expect(app().textContent).toContain('R3C3 사용 중')
    fireEvent.click(screen.getByRole('button', { name: '다시 보기' }))
    goTo(5)
    expect(screen.queryByRole('group', { name: /처음 본 조건에서 예측/ })).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: '조건을 바꿔 비교하기' }))
    expect(screen.getByRole('radio', { name: '3개' })).toHaveProperty('checked', true)
    expect(save).not.toHaveBeenCalled()
  })
  it('keeps comparison controls before the scene, preserves radio focus and moves focus only at manual boundaries or condition restart', () => {
    render(<TransactionLesson onBack={() => {}} />)
    const forward = screen.getByRole('button', { name: '다음 장면' })
    forward.focus(); next()
    expect(document.activeElement).toBe(forward)
    const previous = screen.getByRole('button', { name: '이전 장면' })
    previous.focus(); fireEvent.click(previous)
    expect(document.activeElement).toBe(screen.getByRole('heading', { name: '트랜잭션 시작 전' }))
    forward.focus(); goTo(11)
    expect(document.activeElement).toBe(forward)
    next()
    expect(document.activeElement).toBe(screen.getByRole('heading', { name: '남은 연결 반납' }))
    fireEvent.click(screen.getByRole('button', { name: '다른 상황 예측하기' }))
    const prediction = screen.getByRole('group', { name: /별개의 새 상황/ })
    expect(document.activeElement).toBe(within(prediction).getAllByRole('radio')[0])
    fireEvent.click(within(prediction).getByRole('radio', { name: '42번 행의 UPDATE를 진행할 수 있다' }))
    fireEvent.click(within(prediction).getByRole('button', { name: '선택과 이유 확인' }))
    fireEvent.click(screen.getByRole('button', { name: '조건을 바꿔 비교하기' }))
    const bar = screen.getByRole('group', { name: '학습 조건 비교' })
    const firstRadio = within(bar).getByRole('radio', { name: '2개' })
    expect(document.activeElement).toBe(firstRadio)
    expect(bar.compareDocumentPosition(pool().closest('.sp-flow-scene')!) & Node.DOCUMENT_POSITION_FOLLOWING).not.toBe(0)
    const thirdConnection = within(bar).getByRole('radio', { name: '3개' })
    thirdConnection.focus()
    const focus = vi.spyOn(HTMLElement.prototype, 'focus')
    const scroll = vi.spyOn(HTMLElement.prototype, 'scrollIntoView')
    fireEvent.click(thirdConnection)
    expect(document.activeElement).toBe(thirdConnection)
    expect(focus).not.toHaveBeenCalled(); expect(scroll).not.toHaveBeenCalled()
    focus.mockRestore(); scroll.mockRestore()
    const replay = screen.getByRole('button', { name: '이 조건으로 처음부터 보기' })
    replay.focus(); fireEvent.click(replay)
    expect(screen.queryByRole('group', { name: '학습 조건 비교' })).toBeNull()
    expect(document.activeElement).toBe(screen.getByRole('heading', { name: '트랜잭션 시작 전' }))
    goTo(5)
    expect(screen.getByRole('radio', { name: '3개' })).toHaveProperty('checked', true)
  })
  it('stops finite playback at the prediction, pauses motion, clears timers and offers identical static reduced-motion steps', () => {
    vi.useFakeTimers()
    const view = render(<TransactionLesson onBack={() => {}} />)
    fireEvent.click(screen.getByRole('button', { name: '재생' }))
    act(() => { vi.advanceTimersByTime(3300) })
    fireEvent.click(screen.getByRole('button', { name: '일시정지' }))
    expect(pool().closest('.sp-flow-scene')?.getAttribute('data-motion-paused')).toBe('true')
    act(() => { vi.advanceTimersByTime(9999) })
    expect(screen.getByRole('heading', { name: 'BEGIN · 작업 묶음 시작' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: '재생' }))
    for (let index = 0; index < 4; index++) act(() => { vi.advanceTimersByTime(3300) })
    expect(screen.getByRole('heading', { name: '세 번째 요청 도착' })).toBeTruthy()
    expect(screen.getByRole('button', { name: '재생' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: '재생' }))
    view.unmount(); expect(vi.getTimerCount()).toBe(0)
    vi.spyOn(window, 'matchMedia').mockReturnValue({ matches: true, addEventListener: vi.fn(), removeEventListener: vi.fn() } as unknown as MediaQueryList)
    render(<TransactionLesson onBack={() => {}} />)
    expect(screen.getByRole('button', { name: '재생' })).toHaveProperty('disabled', true)
    fireEvent.keyDown(screen.getByRole('button', { name: '다음 장면' }), { key: 'ArrowRight' })
    expect(screen.getByRole('heading', { name: 'BEGIN · 작업 묶음 시작' })).toBeTruthy()
  })
})
