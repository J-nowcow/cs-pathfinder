// @vitest-environment happy-dom
import { act, cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { renderToStaticMarkup } from 'react-dom/server'
import { afterEach, describe, expect, it, vi } from 'vitest'
import WebRequestPage, { dynamic, metadata } from '@/app/learn/web-request/page'
import { WebRequestLesson } from '@/components/web-request/WebRequestLesson'

const clock = () => screen.getByRole('slider', { name: /현재 장면/ })
function end() { fireEvent.change(clock(), { target: { value: (clock() as HTMLInputElement).max } }) }
function send() { fireEvent.click(screen.getByRole('button', { name: /조회 요청 보내기|두 번째 요청 보내기/ })) }
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.useRealTimers() })
describe('web request lesson', () => {
  it('serves static canonical no-JS content without reading or writing records or requesting services', () => {
    const get = vi.spyOn(Storage.prototype, 'getItem'); const set = vi.spyOn(Storage.prototype, 'setItem'); const fetcher = vi.spyOn(globalThis, 'fetch')
    const html = renderToStaticMarkup(<WebRequestPage />)
    expect(dynamic).toBe('force-static')
    expect(new URL(metadata.alternates!.canonical as string).pathname).toBe('/learn/web-request')
    expect(html).toContain('data-web-request-interactive="true"')
    expect(html).toContain('.wr-lesson[data-web-request-interactive]{display:none!important}')
    expect(html).toContain('<noscript>'); expect(html).toContain('GET /counters/7'); expect(html).toContain('WHERE id = 7')
    render(<WebRequestLesson />); send(); end()
    expect(get).not.toHaveBeenCalled(); expect(set).not.toHaveBeenCalled(); expect(fetcher).not.toHaveBeenCalled()
  })
  it('shows each boundary, receives two new responses on W1 and keeps C1 in the pool after web close', () => {
    render(<WebRequestLesson />); send()
    const app = screen.getByRole('region', { name: '앱 서버의 처리 코드' })
    expect(document.activeElement).toBe(screen.getByRole('heading', { name: 'HTTP 요청 전송' }))
    fireEvent.change(clock(), { target: { value: '3' } })
    expect(screen.getByLabelText('C1 DB 연결 앱이 사용 중')).toBeTruthy()
    fireEvent.change(clock(), { target: { value: '5' } })
    expect(app.textContent).toContain('조회 결과 0')
    expect(screen.getByLabelText('C1 DB 연결 앱이 사용 중')).toBeTruthy()
    fireEvent.change(clock(), { target: { value: '6' } })
    expect(screen.getByLabelText('C1 DB 연결 사용 가능')).toBeTruthy()
    expect(screen.getByRole('region', { name: '브라우저' }).textContent).toContain('아직 받지 않았습니다')
    end(); expect(screen.getByRole('region', { name: '브라우저' }).textContent).toContain('{"value":0}')
    send(); end()
    const counts = screen.getByLabelText('실행 횟수')
    expect(counts.textContent).toContain('보낸 SELECT 2')
    fireEvent.click(screen.getByRole('button', { name: '웹 연결 W1만 닫기' }))
    expect(document.activeElement).toBe(screen.getByRole('heading', { name: 'W1 닫힘' }))
    expect(screen.getByLabelText('W1 웹 연결 닫힘')).toBeTruthy(); expect(screen.getByLabelText('C1 DB 연결 사용 가능')).toBeTruthy()
    expect(screen.getByRole('button', { name: 'W1이 닫혀 있습니다' })).toHaveProperty('disabled', true)
  })
  it('offers an unseen code prediction before comparison and permits wrong answers or an explicit skip', () => {
    render(<WebRequestLesson />)
    expect(screen.queryByRole('radio', { name: '코드의 고정값 0 보내기' })).toBeNull()
    send(); end()
    expect(screen.getByText('return HTTP(200, {"version": 1})')).toBeTruthy()
    fireEvent.click(screen.getByRole('radio', { name: '필요하다' }))
    fireEvent.change(screen.getByRole('textbox'), { target: { value: '두 구간을 확인해 본다.' } })
    fireEvent.click(screen.getByRole('button', { name: '이유 확인하고 코드 비교하기' }))
    expect(document.activeElement).toBe(screen.getByRole('radio', { name: 'DB에서 값 읽기' }))
    expect(screen.getByText(/이 \/version 코드는 DB를 읽지 않아/)).toBeTruthy()
    const constant = screen.getByRole('radio', { name: '코드의 고정값 0 보내기' }); constant.focus(); fireEvent.click(constant)
    expect(document.activeElement).toBe(constant)
    send(); end()
    expect(screen.getByLabelText('실행 횟수').textContent).toContain('보낸 SELECT 0')
    expect(screen.getByRole('region', { name: 'DB 조회' }).textContent).toContain('이 코드는 DB를 조회하지 않습니다')
    cleanup(); render(<WebRequestLesson />); send(); end()
    fireEvent.click(screen.getByRole('button', { name: '예측 건너뛰고 비교하기' }))
    expect(screen.getByRole('radio', { name: '코드의 고정값 0 보내기' })).toBeTruthy()
  })
  it('does not offer a no-op close or comparison from a historical received frame', () => {
    render(<WebRequestLesson />); send(); end(); send(); end()
    fireEvent.change(clock(), { target: { value: '8' } })
    expect(screen.queryByRole('button', { name: '웹 연결 W1만 닫기' })).toBeNull()
    expect(screen.queryByRole('button', { name: '예측 건너뛰고 비교하기' })).toBeNull()
  })
  it('plays a finite trace, pauses motion and timers, and cleans up when leaving', () => {
    vi.useFakeTimers(); const view = render(<WebRequestLesson />); send()
    act(() => { vi.advanceTimersByTime(2200) })
    fireEvent.click(screen.getByRole('button', { name: '멈춤' }))
    const scene = view.container.querySelector('.wr-scene')!
    expect(scene.getAttribute('data-motion-paused')).toBe('true')
    act(() => { vi.advanceTimersByTime(30000) })
    expect(screen.getByRole('heading', { name: '앱 코드 실행' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: '재생' }))
    for (let index = 0; index < 6; index++) act(() => { vi.advanceTimersByTime(2200) })
    expect(screen.getByRole('heading', { name: '브라우저 수신 완료' })).toBeTruthy()
    expect(screen.getByRole('button', { name: '재생' })).toHaveProperty('disabled', true)
    expect(vi.getTimerCount()).toBe(0)
    fireEvent.click(screen.getByRole('button', { name: '같은 W1으로 두 번째 요청 보내기' }))
    view.unmount(); expect(vi.getTimerCount()).toBe(0)
  })
  it('keeps reduced-motion steps static and uses native timeline and keyboard navigation', () => {
    vi.spyOn(window, 'matchMedia').mockReturnValue({ matches: true, addEventListener: vi.fn(), removeEventListener: vi.fn() } as unknown as MediaQueryList)
    render(<WebRequestLesson />); send()
    expect(screen.getByRole('button', { name: '재생' })).toHaveProperty('disabled', true)
    const next = screen.getByRole('button', { name: '다음 장면' }); next.focus(); fireEvent.keyDown(next, { key: 'ArrowRight' })
    expect(screen.getByRole('heading', { name: '앱 코드 실행' })).toBeTruthy(); expect(document.activeElement).toBe(next)
    fireEvent.change(clock(), { target: { value: '8' } })
    expect(within(screen.getByRole('region', { name: '브라우저' })).getByText('{"value":0}')).toBeTruthy()
  })
})
