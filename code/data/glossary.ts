/**
 * 용어 사전. **그래프와 별개로 운영한다.**
 *
 * 질문 그래프에 용어를 노드로 넣지 않는 이유 — 꼬리질문은 "한 층 더 깊은
 * 새 질문"이지 정의가 아니다. 용어를 질문으로 만들면 그래프가 정의로
 * 오염된다. 대신 본문 속 용어의 **첫 등장**을 개념 페이지로 잇고, 거기서
 * 사전의 한 줄 뜻과 관련 면접 질문을 함께 보여 준다.
 *
 * 등재 기준은 빈도 실측이다. 본문 335편에서 3편 이상에 나오는 용어만
 * 실었다(2026-08-10, 75개). 문턱을 5편에서 3편으로 내리면서 40여 개가
 * 들어왔다.
 *
 * **재는 자리가 링크가 걸리는 자리와 같아야 한다.** 처음 스캔은 본문
 * 문자열을 통째로 셌는데, 그러면 도식과 코드 속 등장까지 세어 실제보다
 * 부풀려진다. `데드락`이 대표적이다 — 원문에 13번 나오지만 문단에 홑으로
 * 선 것은 1편뿐이라 링크가 거의 안 걸린다. 그래서 blocks → inline 파서를
 * 태워 **linkify가 실제로 보는 text 토큰만** 다시 셌다.
 *
 * 실측에 나왔지만 뺀 것과 이유:
 * - `불변` — 일반 형용사("불변이다")와 겹쳐 오탐이 난다
 * - `그래프`(8편) · `인터페이스`(11편) — 차트, 화면이라는 일상 뜻과 겹친다
 * - `락`(10편) — 한 글자라 오탐 대가가 크다
 * - `재시도` · `왕복` · `커넥션` — 낱말에서 뜻이 그대로 읽힌다
 * 짧고 흔한 낱말은 빈도가 높아도 빼는 쪽이 맞다.
 *
 * **뜻은 한 문장, 조건부를 법칙처럼 쓰지 않는다.** B7에서 손으로 쓴
 * 11편 중 7편이 틀렸는데 전부 조건부인 것을 단정해서였다. 여기 뜻이
 * 틀리면 모든 본문에서 링크로 노출되므로 본문 오류보다 비싸다.
 *
 * 정적 파일이다. DB를 안 쓴다 — 용어는 사람이 쓰고 큐레이션된 것만
 * 나가야 하며, GitHub에서 고칠 수 있어야 한다.
 */
