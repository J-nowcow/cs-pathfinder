import { after } from 'next/server'

/**
 * 응답을 보낸 뒤에 할 일을 건다. 요청 컨텍스트가 없으면 조용히 버린다.
 *
 * `after()`는 Next 요청 컨텍스트 밖에서 **동기적으로 던진다**
 * (`workAsyncStorage`가 비어 있을 때). 시험이 라우트 핸들러를 직접
 * 부르는 이 저장소의 관례에서는 그 경로를 매번 탄다. 그것 때문에
 * 본 응답이 500이 되면 안 된다.
 *
 * **버려진 일은 호출자가 스스로 회복해야 한다.** 이 함수는 재시도를
 * 해 주지 않는다 — 임베딩 백필이라면 매일 스윕이 줍고, 조회수라면
 * 한 번쯤 안 세도 된다. 회복 경로가 없는 일을 여기에 걸면 안 된다.
 */
export function safeAfter(work: () => void | Promise<void>): void {
  try {
    after(work)
  } catch {
    /* 요청 컨텍스트 밖(주로 시험). 호출자의 회복 경로가 감당한다 */
  }
}
