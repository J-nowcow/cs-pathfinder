/**
 * 임베딩 모델과 차원.
 *
 * **질의와 문서가 같은 모델이어야 벡터가 맞는다.** 다른 모델로 만든 벡터를
 * 견주면 숫자는 나오지만 뜻이 없다. 그래서 한 곳에 두고 양쪽이 여기서 읽는다.
 *
 * `bge-m3`를 고른 이유는 **런타임에 부를 일이 없기 때문**이다.
 * `collectCandidates`는 사용자 입력이 아니라 **부모 노드**를 기준으로 후보를
 * 뽑는다. 부모는 이미 있는 노드라 벡터가 미리 계산돼 있다. 비교만 하면 되니
 * 모델이 어디서 도는지가 상관없다.
 *
 * 그래서 로컬에서 만든다. 무료 한도도, 위탁 처리자도, 지연도 없다.
 * 밤에 한 번 채우고 낮에는 읽기만 한다.
 *
 * **나중에 사용자가 친 문장으로 전역 검색을 하고 싶어지면** 그때는 런타임에
 * 같은 모델을 불러야 한다. 그 경우 로컬은 성립하지 않고 호스팅 모델로
 * 갈아타야 하며, **문서 쪽도 전부 다시 임베딩해야 한다.** 그래서 무엇으로
 * 만들었는지를 아래 상수로 남긴다.
 */

/** ollama 모델 이름. `ollama pull`로 받는 것과 글자 하나까지 같아야 한다 */
export const EMBED_MODEL = 'bge-m3'

/**
 * 차원.
 *
 * SQL의 `::vector(N)` 캐스팅에 그대로 들어간다. 실제 벡터와 어긋나면
 * Postgres가 거부하므로 조용히 틀리지는 않는다.
 */
export const EMBED_DIM = 1024

/**
 * 후보로 데려올 이웃 수.
 *
 * `MAX_CANDIDATES`(50) 전부를 임베딩으로 채우지 않는다. 구조와 의미 관계가
 * 먼저 차고 남는 자리에만 들어가야 하는데, 상한을 안 두면 임베딩이 그
 * 순서를 밀어낸다. 가장 가까운 몇 개만 데려온다.
 */
export const EMBED_TOP_K = 12

/**
 * 이만큼도 안 닮았으면 후보로 안 넣는다.
 *
 * 코사인 유사도다. 문턱이 없으면 **가장 안 닮은 것도 top-k에 올라온다** --
 * 이웃이 12개보다 적을 때 그렇게 된다. 게이트가 걸러 주긴 하지만 프롬프트에
 * 쓰레기를 넣으면 판정이 헐거워진다("고를 것이 많으면 아무거나 고른다").
 *
 * **실측으로 정했다.** 321편 51,360쌍의 분포(`npm run embed -- --probe`):
 *
 *   중앙값 0.430 · 90분위 0.517 · 99분위 0.611 · 최대 0.994
 *
 * 처음에 0.5로 잡았다가 고쳤다. **중앙값이 0.430이라 0.5는 상위 10%를
 * 통과시킨다** -- 노드당 30개가 넘게 쏟아진다. `bge-m3`의 한국어 유사도가
 * 전반적으로 높은 쪽에 몰려 있어서, 다른 모델의 감각으로 잡으면 틀린다.
 *
 * 0.7은 99분위보다 위다. 눈으로 본 쌍에서 이 값을 넘는 것은 전부 실제로
 * 같거나 거의 같은 질문이었다(`#168`/`#266` 0.994, `#4`/`#234` 0.936).
 * 게이트가 묻는 것이 "같은 질문인가"이므로 이 정도가 맞다.
 *
 * **관계 판정(`shortlist`)은 문턱이 달라야 한다.** 거기서 찾는 것은
 * "같은 것"이 아니라 "다르지만 관련된 것"이라 더 낮게 잡아야 한다.
 */
export const EMBED_MIN_SIMILARITY = 0.7

/**
 * 관계 후보의 문턱. 매칭보다 낮다.
 *
 * 찾는 것이 다르다. 매칭은 **같은 질문**을 찾고, 관계는 **다르지만 이어지는
 * 질문**을 찾는다. 같은 문턱을 쓰면 관계가 중복만 잇고 만다 -- 그러면
 * `shares_concept`이 사실상 `duplicate_of`가 된다.
 *
 * 같은 분포에서 0.5는 상위 10% 근처다(90분위 0.517). 위쪽 24개만 물어보므로
 * 문턱이 하는 일은 **쓰레기를 자르는 것**이지 순위를 정하는 것이 아니다.
 *
 * 낱말 겹침이 하던 일과 견주면 이쪽이 훨씬 넓다. 낱말 방식은 겹치는 낱말이
 * 하나도 없으면 후보에서 아예 빼 버렸다 -- `"GC 멈춤"`과 `"STW는 왜 필요한가"`가
 * 그래서 영영 안 이어졌다.
 */
export const RELATION_MIN_SIMILARITY = 0.5
