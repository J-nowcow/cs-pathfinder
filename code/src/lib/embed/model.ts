/**
 * 임베딩 모델과 차원.
 *
 * **질의와 문서가 같은 모델이어야 벡터가 맞는다.** 다른 모델로 만든 벡터를
 * 견주면 숫자는 나오지만 뜻이 없다. 그래서 한 곳에 두고 양쪽이 여기서 읽는다.
 *
 * **호스팅 모델(Gemini)을 쓴다.** 처음엔 로컬 ollama `bge-m3`였다 — 후보를
 * 부모 노드 기준으로 뽑으므로 런타임 모델 호출이 없고, 로컬 배치로 충분하다고
 * 봤다. 그런데 신규 노드를 채우는 경로가 전부 **내 맥에 매여 있었다.** 맥이
 * 꺼지면 밀리고, fork한 기여자는 배치를 스스로 지어야 한다. debate로 견준
 * 결과(D3-lite, 2026-08-09) 이미 매일 도는 GitHub Actions + 이미 있는
 * Gemini 키 쪽이 운영 신뢰성·기여자 재현성에서 이겼다.
 *
 * 전환 비용은 전량 재임베딩이었다. 모델이 다르면 벡터 공간이 달라서
 * bge-m3로 만든 321편을 전부 버리고 다시 만들었다.
 */

/**
 * Gemini 임베딩 모델. 스펙 §5가 지정한 그 모델이다.
 *
 * 무료 티어 입력이 무료고, 이미 해설 생성에 쓰는
 * `GOOGLE_GENERATIVE_AI_API_KEY`를 같이 쓴다 — 위탁 처리자가 안 늘어난다.
 * (`/privacy` 4번 항목의 목적 문구에 임베딩을 함께 적었다.)
 */
export const EMBED_MODEL = 'gemini-embedding-001'

/**
 * 차원. SQL의 `::vector(N)` 캐스팅에 그대로 들어간다.
 *
 * 기본 3072를 MRL(Matryoshka)로 768까지 줄여 받는다. 공식 권장 절단점이
 * 768·1536·3072이고, 질문 한 문장의 유사도에는 768이면 충분하다.
 * 3072는 행당 12KB라 321편에도 부담이 없지만 늘릴 이유도 없다.
 *
 * **주의: 3072가 아닌 차원은 정규화가 안 돼서 온다**(공식 문서).
 * `gemini.ts`가 받아서 L2 정규화한 뒤에 내보낸다.
 */
export const EMBED_DIM = 768

/**
 * 후보로 데려올 이웃 수.
 *
 * `MAX_CANDIDATES`(50) 전부를 임베딩으로 채우지 않는다. 구조와 의미 관계가
 * 먼저 차고 남는 자리에만 들어가야 하는데, 상한을 안 두면 임베딩이 그
 * 순서를 밀어낸다. 가장 가까운 몇 개만 데려온다.
 */
export const EMBED_TOP_K = 12

/**
 * 이만큼도 안 닮았으면 후보로 안 넣는다.
 *
 * 코사인 유사도다. 문턱이 없으면 **가장 안 닮은 것도 top-k에 올라온다** --
 * 이웃이 12개보다 적을 때 그렇게 된다.
 *
 * **모델을 바꾸면 반드시 다시 잰다.** bge-m3 시절 이 값을 감으로 0.5로
 * 잡았다가 실측(중앙값 0.430)에 뒤집혔고, gemini로 갈아탈 때도 bge에서
 * 정한 0.7이 **새 분포의 중앙값(0.722) 아래**라 절반을 통과시키는 값이
 * 됐다. 모델마다 유사도가 몰리는 자리가 다르므로 남의 감각을 이월하면
 * 두 번 다 틀린다.
 *
 * 실측(2026-08-09, gemini-embedding-001 · 768차원 · SEMANTIC_SIMILARITY,
 * 321편 51,360쌍):
 *
 *   중앙값 0.722 · 90분위 0.765 · 99분위 0.816 · 최대 0.997
 *
 * 0.85는 99분위보다 위다. 눈으로 본 상위 쌍에서 0.93 위는 전부 사실상
 * 같은 질문이었고(`#168`/`#266` 0.997, `#4`/`#234` 0.961), 0.85~0.93
 * 사이는 상위 20쌍에 아예 없었다 — 이 말뭉치에서 그 구간은 거의 비어
 * 있다. 게이트가 묻는 것이 "같은 질문인가"이므로 그 빈 틈 아래(0.85)에
 * 문턱을 둔다.
 */
export const EMBED_MIN_SIMILARITY = 0.85

/**
 * 관계 후보의 문턱. 매칭보다 낮다.
 *
 * 찾는 것이 다르다. 매칭은 **같은 질문**을 찾고, 관계는 **다르지만 이어지는
 * 질문**을 찾는다. 같은 문턱을 쓰면 관계가 중복만 잇고 만다 -- 그러면
 * `shares_concept`이 사실상 `duplicate_of`가 된다.
 *
 * 위쪽 24개만 물어보므로 문턱이 하는 일은 **쓰레기를 자르는 것**이지
 * 순위를 정하는 것이 아니다. 이 값도 모델을 바꾸면 같이 다시 잰다.
 *
 * 0.76은 위 실측 분포의 90분위(0.765) 자리다. bge 시절 0.5가 그때
 * 분포의 90분위(0.517) 근처였던 것과 같은 자리를 새 분포에서 다시
 * 잡은 것이다 — 값은 다르지만 "상위 10%만 물어본다"는 뜻이 같다.
 */
export const RELATION_MIN_SIMILARITY = 0.76
