import type { ContentIssue } from '@/lib/llm/content-rules'

/**
 * 교과서가 낡아서 배운 대로 쓰면 틀리는 자리.
 *
 * **검사기는 원래 형태만 본다.** 문단 길이, 도식 위치, 문체. 틀린 내용은
 * 하나도 못 잡는다. `~를 통해`를 46편에서 잡아내면서 "다익스트라는 양수
 * 가중치에서만 쓴다"는 그냥 통과시킨다.
 *
 * 사실 확인 전체를 규칙으로 할 수는 없다. 그건 대조 모델이 할 일이다. 다만
 * 표본 20편을 대조해 보니 틀린 것들이 **한 종류로 모였다** — 교과서에 그대로
 * 실려 있는데 현실이 바뀐 자리다. 모델이 학습한 대로 쓰면 틀린다. 그런 자리는
 * 몇 개 안 되고 문장 모양도 거의 정해져 있어서 규칙으로 잡을 수 있다.
 *
 * **정밀도가 재현율보다 중요하다.** 여기 걸리면 다시 부르므로(block) 오탐은
 * 14초를 버리고 멀쩡한 답을 나쁜 답으로 바꿀 수 있다. 그래서 두 조건을 건다 —
 * 주제어가 근처에 있어야 하고, 틀린 표현이 정확히 있어야 한다. 넓게 잡는 대신
 * 확실한 것만 잡는다.
 *
 * 운영 코퍼스 276편에 돌려 오탐을 셌다. 아래 주석에 그 수를 적어 둔다.
 */

type StaleFact = {
  /** 지적 이름. 집계할 때 이 값으로 묶는다 */
  rule: string
  /** 이 주제를 다루는 글에서만 본다. 없으면 아예 안 본다 */
  topic: RegExp
  /** 이것이 있으면 낡은 답이다 */
  wrong: RegExp
  /**
   * 이것도 있으면 봐준다.
   *
   * **오탐이 여기서 나왔다.** 코퍼스에 돌려 보니 아홉 건 중 둘이 오탐이었고,
   * 둘 다 같은 모양이었다 — **낡은 표현을 쓰면서 곧바로 현대적 설명을 덧붙인**
   * 글이다. "공개키로 대칭키를 전달한다"고 쓴 다음 줄에서 "TLS는 세션 키를
   * 합의한다"고 바로잡거나, "TLB를 비운다"고 쓴 다음 "ASID로 줄인다"고 잇는다.
   *
   * 그런 글은 틀리지 않았다. 오히려 둘 다 아는 글이다.
   */
  unless?: RegExp
  /** 모델에게 돌려줄 말. 무엇이 맞는지까지 적는다 */
  detail: string
}

/**
 * 주제어와 틀린 표현이 **같은 글 안에** 있어야 잡는다.
 *
 * 문단 단위로 좁히지 않는다. 도식과 문단에 나뉘어 쓰이는 경우가 실제로 있다 —
 * `Key Exchange | 프리마스터 시크릿 전달`은 도식 안이고 주제어는 첫 문단이다.
 */
const STALE: StaleFact[] = [
  {
    /*
     * TLS 키 교환. 표본 20편 중 둘이 이 모양이었다 — 가장 자주 나온 오류다.
     *
     * TLS 1.3은 RSA 키 전송을 **아예 제거했고** 1.2도 현실에서는 대부분
     * (EC)DHE다. 대칭키를 실어 보내지 않고 양쪽이 공유 비밀을 합의한다.
     */
    rule: '낡은사실:TLS키교환',
    topic: /TLS|HTTPS|SSL|핸드셰이크/,
    wrong:
      /(비대칭|공개)키로\s*(그\s*)?(대칭키|세션\s*키)[를을]?\s*(안전하게\s*)?(전달|전송|보내)|프리마스터\s*시크릿[를을]?\s*(전달|전송|보내)/,
    /* 키를 합의한다고 어디선가 말했으면 현대적 그림을 이미 알고 있는 글이다 */
    unless: /합의|DHE|디피[\s·-]?헬만|Diffie/i,
    detail:
      'TLS를 "비대칭키로 대칭키를 전달"·"프리마스터 시크릿 전달"로 설명했다. TLS 1.3은 그 방식을 제거했고 1.2도 현실에서는 (EC)DHE다. 공개키는 서명으로 서버를 인증하고, 공유 비밀은 양쪽이 합의해 만든 뒤 거기서 대칭키를 파생한다',
  },
  {
    /* 보통 TLS는 서버만 인증한다. 상호 인증은 mTLS라는 별도 선택이다 */
    rule: '낡은사실:TLS상호인증',
    topic: /TLS|HTTPS|SSL|핸드셰이크/,
    wrong: /서로의?\s*(신원|신분)[를을]?\s*(확인|검증|인증)/,
    detail:
      'TLS가 "서로의 신원을 확인한다"고 썼다. 보통은 클라이언트가 서버를 인증하고 그 반대는 안 한다. 상호 인증은 mTLS라는 별도 선택이다',
  },
  {
    /*
     * 교착 상태의 예방과 회피. 이 둘을 가르는 것이 운영체제 시험 문제 그
     * 자체라 바꿔 쓰면 감점이 크다.
     *
     * 회피는 네 조건을 그대로 두고 요청마다 안전 상태인지 검사한다.
     * 조건 자체를 없애는 것이 예방이다.
     */
    rule: '낡은사실:교착회피정의',
    topic: /교착|데드락|deadlock/i,
    wrong:
      /회피[는란]?[^.\n]{0,40}(발생|생길|일어날)[^.\n]{0,20}(상황|조건)[를을]?[^.\n]{0,20}(아예\s*)?(만들지\s*않|없애|제거|차단)/,
    detail:
      '"회피"를 조건 자체를 없애는 것으로 설명했다. 그것은 예방(prevention)이다. 회피(avoidance)는 네 조건을 그대로 두고 요청마다 안전 상태인지 검사해 안전할 때만 내주는 것이다(은행원 알고리즘)',
  },
  {
    /* 0 가중치 간선이 있는 문제에서 판단이 갈린다. 한 글자 차이다 */
    rule: '낡은사실:다익스트라조건',
    topic: /다익스트라|Dijkstra/i,
    wrong: /양수\s*(의\s*)?(가중치|간선|비용)|가중치가\s*양수/,
    detail:
      '다익스트라의 조건을 "양수"라고 썼다. 0을 포함한 비음수다. 0 가중치 간선이 있어도 쓸 수 있다',
  },
  {
    /*
     * 컨텍스트 스위칭. 캐시는 전환으로 무효화되지 않고, TLB도 PCID·ASID를
     * 쓰면 통째로 비우지 않는다. 오래된 교과서에 그대로 있는 서술이다.
     */
    rule: '낡은사실:전환시캐시무효화',
    topic: /컨텍스트\s*스위칭|문맥\s*교환|context\s*switch/i,
    wrong:
      /(캐시|TLB)[^.\n]{0,30}(통째로\s*)?(비운다|비워진다|무효화|플러시|flush)|(비운다|무효화)[^.\n]{0,15}(캐시|TLB)/i,
    /* PCID·ASID를 언급했으면 통째로 비우지 않는다는 것을 이미 아는 글이다 */
    unless: /PCID|ASID/i,
    detail:
      '전환할 때 캐시나 TLB를 비운다고 썼다. CPU 캐시는 전환으로 무효화되지 않고 작업 집합이 충돌해 밀려날 뿐이다. TLB도 PCID(x86-64)·ASID(ARM)를 쓰면 프로세스 전환에서 통째로 비우지 않는다',
  },
]

/**
 * 낡은 답이 있는지 본다.
 *
 * `block`이다. 여기 걸린 것은 **틀린 내용**이라 화면이 멀쩡해도 소용없다.
 * 형태 규칙과 성격이 다르다 — 읽기 좋은 오답은 읽기 나쁜 정답보다 나쁘다.
 */
export function staleFactIssues(body: string): ContentIssue[] {
  const out: ContentIssue[] = []
  for (const s of STALE) {
    if (!s.topic.test(body)) continue
    if (!s.wrong.test(body)) continue
    if (s.unless?.test(body)) continue
    out.push({ rule: s.rule, detail: s.detail, severity: 'block' })
  }
  return out
}
