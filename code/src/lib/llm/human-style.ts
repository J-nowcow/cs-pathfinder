function intentOf(input: string): WritingIntent {
  if (/차이|비교|고르|선택|\bvs\.?\b|무엇으로/.test(input)) return 'choice'
  if (/장애|실패|복구|재시도|retry|circuit|timeout|타임아웃|fallback|폴백/i.test(input)) {
    return 'recovery'
  }
  if (/순서|과정|흐름|단계|핸드셰이크|요청.+거치|입력.+무슨 일|어떻게 동작/.test(input)) {
    return 'sequence'
  }
  if (/URL|DNS|TCP|TLS|HTTP|렌더링|연결 수립|요청 처리/i.test(input)) return 'sequence'
  if (/왜|비용|느려|성능|병목|인덱스|오버헤드|복잡도/.test(input)) return 'cost'
  return 'cost'
}

