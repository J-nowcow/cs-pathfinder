--
-- 원본은 `data/node-tags.ts`(질문 키 매핑)이고 통제 어휘는 `data/tags.ts`다.
-- DB는 시드가 채우는 사본이다.
--
-- text[]로 둔다. 태그 표를 따로 만들어 조인하는 것은 322행 규모에서
-- 이득이 없고, 통제 어휘 검증은 시험이 파일 차원에서 한다.
alter table qnode add column tags text[] not null default '{}';
