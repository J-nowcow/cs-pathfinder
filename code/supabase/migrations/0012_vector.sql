-- 유사도 검색을 켠다.
--
-- `0005`가 임베딩 컬럼을 `real[]`로 두면서 "유사도 연산이 필요해지는 시점에
-- vector로 옮긴다. 값은 그대로 살아 있다"고 적었다. 그 시점이 왔는데
-- **컬럼은 안 옮긴다.** 옮길 필요가 없다는 것을 실측했다.
--
--   ('{1,0,0,0}'::real[])::vector(4)  →  [1,0,0,0]
--
-- 캐스팅이 되므로 질의에서 `embedding::vector(1024)`로 쓰면 그만이다.
-- 행이 321개인 지금 컬럼 전환과 HNSW 인덱스는 순차 스캔보다 느리고,
-- 전환은 되돌리기 어려운 쓰기다. 행이 수천이 되면 그때 옮긴다 --
-- 캐스팅이 되니 **그때도 백필은 필요 없다.**
--
-- 이 마이그레이션이 하는 일은 `<=>` 연산자를 쓸 수 있게 만드는 것뿐이다.
--
-- PGlite에서는 인스턴스를 만들 때 확장을 넘겨야 이 줄이 산다
-- (`src/lib/db/client.ts`의 `createPglite`). 안 넘기면
-- `extension "vector" is not available`로 죽고 DB 시험 전부가 첫 줄에서 멈춘다.
--
-- Neon에는 0.8.0이 가용한 것을 확인했다(`pg_available_extensions`).
create extension if not exists vector;
